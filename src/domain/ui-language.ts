export type Translate = (text: string, ...values: (string | number)[]) => string;

export function translator(language: Language): Translate {
  return (text, ...values) => (language === 'en' ? (english[text] ?? text) : text)
    .replace(/\{(\d+)\}/g, (placeholder, index: string) => String(values[Number(index)] ?? placeholder));
}
